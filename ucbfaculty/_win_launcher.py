"""Windows ``.bat`` shortcut writer for ucbfaculty.

The Windows counterpart of :mod:`ucbfaculty._mac_launcher`.  Writes a
small ``.bat`` file to the user's Desktop that double-clicks into the
Panel app via ``pythonw.exe`` (the windowless Python interpreter),
so no black console window flashes on screen.

Why a ``.bat`` and not a real ``.lnk`` shortcut?
------------------------------------------------
A ``.lnk`` shortcut requires either the ``pywin32`` optional
dependency or a PowerShell subprocess to author.  A ``.bat`` is a
plain UTF-8 text file we can write with the standard library alone,
and double-clicking it from the Desktop has the same effect for the
user.  The trade-off is the icon: a ``.bat`` shows the generic
script icon rather than a custom app icon.  Acceptable for now;
swap to ``.lnk`` later if the icon matters.
"""

from __future__ import annotations

import sys
from pathlib import Path


__all__ = [
    "DEFAULT_SHORTCUT_NAME",
    "DEFAULT_PORT",
    "default_destination",
    "write_bat_shortcut",
]


DEFAULT_SHORTCUT_NAME = "UCB Faculty Tools.bat"
DEFAULT_PORT = 5006


def _pythonw_path(python: Path) -> Path:
    """Return the ``pythonw.exe`` sibling of ``python`` if it exists.

    ``pythonw.exe`` doesn't open a console window when invoked, so
    double-clicking the .bat doesn't flash a black box on screen.
    Falls back to the given interpreter if pythonw isn't present
    (some embedded distributions omit it).
    """
    pythonw = python.parent / "pythonw.exe"
    if pythonw.exists():
        return pythonw
    return python


def _bat_script(python: Path, port: int) -> str:
    """Return the contents of the .bat file (CRLF line endings).

    Uses ``start ""`` so the parent ``cmd.exe`` exits immediately;
    the server runs detached from the launcher process.
    """
    pythonw = _pythonw_path(python)
    return (
        "@echo off\r\n"
        "REM UCB Faculty Tools launcher\r\n"
        "REM Generated by `ucbfaculty install-launcher`. Do not edit by hand:\r\n"
        "REM re-run install-launcher to regenerate after upgrading.\r\n"
        f'start "" "{pythonw}" -m ucbfaculty.cli serve --show --port {port}\r\n'
    )


def default_destination() -> Path:
    """Pick the user's Desktop as the natural Windows destination.

    Honors OneDrive-redirected Desktops (``~/OneDrive/Desktop``),
    which are common on Windows 11 setups; falls back to
    ``~/Desktop`` otherwise.
    """
    home = Path.home()
    onedrive_desktop = home / "OneDrive" / "Desktop"
    if onedrive_desktop.is_dir():
        return onedrive_desktop / DEFAULT_SHORTCUT_NAME
    return home / "Desktop" / DEFAULT_SHORTCUT_NAME


def write_bat_shortcut(
    dest: Path | None = None,
    *,
    python: Path | None = None,
    port: int = DEFAULT_PORT,
    force: bool = False,
) -> Path:
    """Write a ``.bat`` launcher to ``dest`` (or the user's Desktop).

    Parameters
    ----------
    dest : Path or None
        Where to write the ``.bat``.  Defaults to
        :func:`default_destination`.
    python : Path or None
        Path to the Python interpreter that has ``ucbfaculty``
        installed.  Defaults to :data:`sys.executable`.  The launcher
        will look for a ``pythonw.exe`` sibling and prefer that.
    port : int
        TCP port the Panel server will bind to.  Defaults to 5006 to
        match ``ucbfaculty serve``; change both together.
    force : bool
        Overwrite an existing file at ``dest`` if present.

    Returns
    -------
    Path
        Absolute path to the written ``.bat`` file.

    Raises
    ------
    RuntimeError
        If called on a non-Windows platform.
    FileExistsError
        If ``dest`` exists and ``force`` is False.
    """
    if sys.platform != "win32":
        raise RuntimeError(
            "Windows .bat shortcut is only supported on Windows "
            f"(detected platform: {sys.platform!r})."
        )

    if dest is None:
        dest = default_destination()
    if python is None:
        python = Path(sys.executable)
    dest = Path(dest).expanduser().resolve()

    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.exists() and not force:
        raise FileExistsError(
            f"{dest} already exists. Pass force=True (--force) to overwrite."
        )

    dest.write_text(_bat_script(python, port=port), encoding="utf-8")
    return dest
