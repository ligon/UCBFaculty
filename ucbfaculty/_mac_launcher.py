"""macOS .app launcher writer for ucbfaculty.

A hand-rolled minimal ``.app`` bundle that double-clicks into the
Panel app -- no PyInstaller, no codesigning, no bundled Python.  The
``.app`` is a thin shell script wrapper that invokes the already-
installed ``ucbfaculty`` package via the Python interpreter it was
generated against (typically ``sys.executable``).

Used by the ``ucbfaculty install-launcher`` CLI subcommand and also
called automatically from the tail of ``ucbfaculty init`` on macOS,
so first-time setup yields a double-clickable app in
``~/Applications`` without further work from the user.

Why hand-rolled rather than PyInstaller?
----------------------------------------
The user already has the package installed via ``pip``.  We just need
a finder-clickable entry point.  A 1-KB .app bundle around the
existing interpreter is faster to build, faster to ship, and avoids
the Gatekeeper "unidentified developer" warning that bites unsigned
PyInstaller bundles.
"""

from __future__ import annotations

import re
import shutil
import stat
import sys
import textwrap
from pathlib import Path


__all__ = [
    "DEFAULT_APP_NAME",
    "DEFAULT_BUNDLE_ID",
    "DEFAULT_PORT",
    "default_destination",
    "write_app_bundle",
]


DEFAULT_APP_NAME = "UCB Faculty Tools"
DEFAULT_BUNDLE_ID = "edu.berkeley.senate.ucbfaculty"
DEFAULT_PORT = 5006


def _short_version(version: str) -> str:
    """Reduce a PEP 440 version string to ``X.Y.Z`` for ``CFBundleShortVersionString``.

    macOS expects ``CFBundleShortVersionString`` to be three dotted
    integers; local-version suffixes (``+gabc1234``) and dev/post tags
    are not allowed.  Strip everything after the first ``MAJOR.MINOR.PATCH``.
    """
    match = re.match(r"(\d+\.\d+\.\d+)", version or "")
    return match.group(1) if match else "0.0.0"


def _info_plist(app_name: str, bundle_id: str, version: str) -> str:
    short = _short_version(version)
    return textwrap.dedent(
        f"""\
        <?xml version="1.0" encoding="UTF-8"?>
        <!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
                              "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
        <plist version="1.0">
        <dict>
            <key>CFBundleName</key><string>{app_name}</string>
            <key>CFBundleDisplayName</key><string>{app_name}</string>
            <key>CFBundleIdentifier</key><string>{bundle_id}</string>
            <key>CFBundleExecutable</key><string>launch</string>
            <key>CFBundleIconFile</key><string>AppIcon</string>
            <key>CFBundlePackageType</key><string>APPL</string>
            <key>CFBundleShortVersionString</key><string>{short}</string>
            <key>CFBundleVersion</key><string>{version or short}</string>
            <key>LSMinimumSystemVersion</key><string>10.13</string>
            <key>NSHighResolutionCapable</key><true/>
            <key>LSUIElement</key><false/>
        </dict>
        </plist>
        """
    )


def _launch_script(python: Path, port: int) -> str:
    """Bash launcher placed at ``Contents/MacOS/launch``.

    Behavior:

    1. If a server is already listening on ``port``, just open the
       browser at the lookup URL and exit.  This makes a second
       double-click a no-op (rather than crashing on a port conflict).
    2. Otherwise ``exec`` the Panel server in the foreground so the
       Dock icon stays around for as long as the app is alive.
       Cmd-Q from the Dock then sends ``SIGTERM`` directly to the
       Python process for a clean shutdown.
    """
    return textwrap.dedent(
        f"""\
        #!/bin/bash
        # UCB Faculty Tools launcher
        # Generated by `ucbfaculty install-launcher`.  Do not edit by hand:
        # re-run install-launcher to regenerate this file after upgrading.
        set -e

        PYTHON={str(python)!r}
        PORT={port}
        LOGDIR="$HOME/Library/Logs/ucbfaculty"
        mkdir -p "$LOGDIR"

        # Already running?  Just open the browser.
        if /usr/sbin/lsof -nP -iTCP:$PORT -sTCP:LISTEN >/dev/null 2>&1; then
            /usr/bin/open "http://localhost:$PORT/lookup"
            exit 0
        fi

        # Fresh start: replace this shell with the server so the Dock
        # icon's Cmd-Q delivers SIGTERM straight to Python.
        exec "$PYTHON" -m ucbfaculty.cli serve --show --port "$PORT" \\
            >> "$LOGDIR/server.log" 2>&1
        """
    )


def default_destination() -> Path:
    """Pick the most user-friendly default destination for the bundle.

    ``~/Applications`` if it already exists (avoids needing sudo for
    ``/Applications``); otherwise ``~/Desktop`` so the user sees the
    .app immediately after install.
    """
    user_apps = Path.home() / "Applications"
    if user_apps.is_dir():
        return user_apps / f"{DEFAULT_APP_NAME}.app"
    return Path.home() / "Desktop" / f"{DEFAULT_APP_NAME}.app"


def write_app_bundle(
    dest: Path | None = None,
    *,
    python: Path | None = None,
    app_name: str = DEFAULT_APP_NAME,
    bundle_id: str = DEFAULT_BUNDLE_ID,
    version: str = "0.0.0",
    port: int = DEFAULT_PORT,
    force: bool = False,
) -> Path:
    """Write a minimal macOS ``.app`` that launches the Panel app on double-click.

    Parameters
    ----------
    dest : Path or None
        Where to write the ``.app`` bundle.  Defaults to
        :func:`default_destination`.
    python : Path or None
        Path to the Python interpreter that has ``ucbfaculty`` installed.
        Defaults to :data:`sys.executable`, which is almost always what
        the caller wants.
    app_name : str
        Display name and bundle filename (without ``.app``).
    bundle_id : str
        Reverse-DNS bundle identifier; harmless if not registered.
    version : str
        Package version for ``CFBundleVersion`` /
        ``CFBundleShortVersionString``.  Usually the caller passes
        ``ucbfaculty.__version__``.
    port : int
        TCP port the Panel server binds to.  Defaults to 5006 to match
        ``ucbfaculty serve`` defaults; change both together.
    force : bool
        Overwrite an existing bundle at ``dest`` if present.

    Returns
    -------
    Path
        The absolute path to the written ``.app`` bundle.

    Raises
    ------
    RuntimeError
        If called on a non-Darwin platform.
    FileExistsError
        If ``dest`` exists and ``force`` is False.
    """
    if sys.platform != "darwin":
        raise RuntimeError(
            "install-launcher is only supported on macOS "
            f"(detected platform: {sys.platform!r})."
        )

    if dest is None:
        dest = default_destination()
    if python is None:
        python = Path(sys.executable)
    dest = Path(dest).expanduser().resolve()

    if dest.exists():
        if not force:
            raise FileExistsError(
                f"{dest} already exists. Pass force=True (--force) to overwrite."
            )
        shutil.rmtree(dest)

    contents = dest / "Contents"
    macos = contents / "MacOS"
    resources = contents / "Resources"
    macos.mkdir(parents=True)
    resources.mkdir(parents=True)

    (contents / "Info.plist").write_text(
        _info_plist(app_name, bundle_id, version), encoding="utf-8"
    )

    launch = macos / "launch"
    launch.write_text(_launch_script(python, port), encoding="utf-8")
    # Make the launcher script executable for everyone who can read it.
    launch.chmod(launch.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    return dest
